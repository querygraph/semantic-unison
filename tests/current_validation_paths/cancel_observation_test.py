"""Tiny disposable receiving files and fabricated helper counters only."""
import hashlib,tempfile,time,unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch
from current_validation_paths.files import Files
from current_validation_paths.cancel_observation import wait

class Observe(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory(prefix='vpc-',dir='/private/tmp');root=Path(self.temp.name);st=root.lstat()
        self.files=Files(root,(st.st_dev,st.st_ino));self.root=self.files.Path(root)
        self.left=self.root/'left';self.right=self.root/'right';self.left.mkdir();self.right.mkdir()
        self.name='cancelled.dng';self.old=b'old private receiver';self.new=self.old+b' incoming generated bytes'
        (self.left/self.name).write_bytes(self.old);(self.right/self.name).write_bytes(self.new)
        self.candidate=self.left/'generated.tmp';self.candidate.write_bytes(self.new);st=self.candidate.lstat();sha=hashlib.sha256(self.new).hexdigest()
        self.record=dict(endpoint='client',mode='hang',pid=101,candidate=str(self.candidate),destination=str(self.left/self.name),
            sha256=sha,size=len(self.new),destination_sha256=hashlib.sha256(self.old).hexdigest(),device=st.st_dev,inode=st.st_ino,
            argv=['--unison-dng-validation-v1','--expected-sha256',sha,'--expected-size',str(len(self.new)),'--threads','1','--',str(self.candidate)])
        self.values=[self.record];self.client=SimpleNamespace(owner=SimpleNamespace(pid=100,reaped=False,terminal=lambda:False))
        self.session=SimpleNamespace(root=self.root,left=self.left,right=self.right,calls=lambda endpoint:self.values)
    def tearDown(self):self.files.close();self.temp.cleanup()
    def observe(self):return wait(self.session,self.name,self.new,self.old,0,self.client,time.monotonic()+1)
    def test_exact_stage_and_old_destination_observed_but_not_settlement(self):
        result=self.observe();self.assertEqual(result['helper'],self.record)
        self.assertFalse(result['helper_settlement_proved']);self.assertFalse(result['resource_release_authorized'])
    def test_changed_stage_or_old_live_or_source_refuses(self):
        for path,data in ((self.candidate,b'corrupt'),(self.left/self.name,b'corrupt'),(self.right/self.name,b'corrupt')):
            with self.subTest(path=str(path)):
                original=path.read_bytes();path.write_bytes(data)
                with self.assertRaises(ValueError):self.observe()
                path.write_bytes(original)
    def test_counter_pid_and_candidate_identity_must_bind(self):
        for key,value in [('pid',True),('pid',100),('inode',0),('endpoint','server'),('mode','pass'),('size',1),('destination_sha256','0'*64)]:
            with self.subTest(key=key,value=value):
                old=self.record[key];self.record[key]=value
                with self.assertRaises(ValueError):self.observe()
                self.record[key]=old
    def test_counter_cannot_redirect_candidate_outside_owned_root(self):
        self.record['candidate']='/unowned/candidate'
        with self.assertRaises(ValueError):self.observe()
    def test_terminal_client_refuses_even_with_complete_record(self):
        self.client.owner.terminal=lambda:True
        with self.assertRaises(ValueError):self.observe()
    def test_two_new_helpers_refuse(self):
        self.values.append(dict(self.record))
        with self.assertRaises(ValueError):self.observe()
    def test_expired_observation_never_uses_complete_record(self):
        with self.assertRaises(TimeoutError):wait(self.session,self.name,self.new,self.old,0,self.client,time.monotonic()-1)
    def test_pending_record_waits_without_signalling(self):
        self.values=[]
        with patch('current_validation_paths.cancel_observation.time.sleep',side_effect=RuntimeError('original inert wait')):
            with self.assertRaisesRegex(RuntimeError,'original inert wait'):self.observe()

if __name__=='__main__':unittest.main()

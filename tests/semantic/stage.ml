let check condition reason=if not condition then failwith reason
let bytes path=let input=open_in_bin path in
  Fun.protect ~finally:(fun () -> close_in input)
    (fun () -> really_input_string input (in_channel_length input))
let write path data=let output=open_out_bin path in output_string output data;close_out output
let refused operation=match operation () with
  | _ -> failwith "expected owner refusal"
  | exception SemanticFile.Invalid _ -> ()
let fixture name operation =
  let root=Filename.concat (Sys.getcwd ()) name in
  Unix.mkdir root 0o700;
  let directory=Filename.concat root "private" and source=Filename.concat root "source" in
  Unix.mkdir directory 0o700;write source "ORIGINAL GENERATED BYTES";
  operation root directory source
let create directory source=ValidationStage.create ~directory ~source ~max_bytes:1024L
let () =
  fixture "normal" (fun _ directory source ->
    let owner=create directory source in
    let original,output=ValidationStage.descriptors owner and stage=ValidationStage.path owner in
    let report=ValidationSnapshot.materialize ~check_cancel:(fun () -> ()) ~max_bytes:1024L
      ~clone:(fun ~expected_length _ _ -> WholeFileClone.platform_decline ~expected_length)
      ~source:original ~output in
    check (report.bytes=24L && bytes stage=bytes source) "stage copied source";
    ValidationStage.check owner;
    write stage "PRIVATE MUTATION";
    ValidationStage.check owner;
    check (bytes source="ORIGINAL GENERATED BYTES") "private stage mutation touched original";
    ValidationStage.retire owner;ValidationStage.retire owner;
    check (not (Sys.file_exists stage) && Sys.readdir directory=[||]) "stage retirement";
    refused (fun () -> ValidationStage.descriptors owner));
  fixture "source-replaced" (fun root directory source ->
    let owner=create directory source in
    Unix.rename source (Filename.concat root "old-original");write source "REPLACEMENT";
    refused (fun () -> ValidationStage.check owner);
    ValidationStage.retire owner;
    check (bytes source="REPLACEMENT" && bytes (Filename.concat root "old-original")="ORIGINAL GENERATED BYTES")
      "source replacement preservation");
  fixture "stage-replaced" (fun root directory source ->
    let owner=create directory source in let stage=ValidationStage.path owner in
    let escaped=Filename.concat root "escaped-owned-stage" in
    Unix.rename stage escaped;write stage "UNOWNED REPLACEMENT";
    refused (fun () -> ValidationStage.check owner);
    (try ValidationStage.retire owner;failwith "replacement cleanup succeeded"
     with ValidationStage.Cleanup_failed _ -> ());
    (try ValidationStage.retire owner;failwith "cleanup failure lost"
     with ValidationStage.Cleanup_failed _ -> ());
    check (bytes stage="UNOWNED REPLACEMENT" && Sys.file_exists escaped && bytes source="ORIGINAL GENERATED BYTES")
      "cleanup removed a replacement";
    check (ValidationStage.uncertain_closes owner=[]) "known cleanup refusal became unknown close");
  fixture "preentry" (fun root directory source ->
    Unix.chmod directory 0o750;refused (fun () -> create directory source);Unix.chmod directory 0o700;
    refused (fun () -> ValidationStage.create ~directory ~source ~max_bytes:1L);
    let link=Filename.concat root "link" in Unix.symlink source link;
    refused (fun () -> create directory link);
    check (Sys.readdir directory=[||] && bytes source="ORIGINAL GENERATED BYTES") "preentry created stage");
  fixture "collision" (fun _ directory source ->
    Random.init 771;
    let a=Random.bits () in let b=Random.bits () in
    let name=Filename.concat directory (Printf.sprintf ".validation-%d-%08x-%08x.dng" (Unix.getpid ()) a b) in
    write name "EXISTING PEER BYTES";Random.init 771;
    (try ignore (create directory source);failwith "collision accepted"
     with Unix.Unix_error (Unix.EEXIST,_,_) -> ());
    check (bytes name="EXISTING PEER BYTES" && bytes source="ORIGINAL GENERATED BYTES")
      "exclusive-create collision removed peer/source");
  fixture "source-edited" (fun _ directory source ->
    let owner=create directory source in
    write source "EXTERNAL USER EDIT WITH DIFFERENT LENGTH";
    refused (fun () -> ValidationStage.check owner);ValidationStage.retire owner;
    check (bytes source="EXTERNAL USER EDIT WITH DIFFERENT LENGTH") "owner overwrote external edit");
  fixture "uncertain-close" (fun root directory source ->
    let owner=create directory source in
    let original,_=ValidationStage.descriptors owner in
    (* Explicit fault: violate borrow lifetime by closing the source first.
       Owner then sees EBADF, retains its uncertain slot; this is not a claim
       about a genuine ambiguous kernel close. Exit later settles test FDs. *)
    Unix.close original;
    (try ValidationStage.retire ~failure:(Failure "original helper error") owner;failwith "unknown close released owner"
     with ValidationStage.Unresolved_ownership held -> check (held==owner) "lost retained owner");
    let records=ValidationStage.uncertain_closes owner in
    check (List.length records=1 && (List.hd records).ValidationStage.descriptor=original) "uncertain fd identity";
    check (match ValidationStage.original_failure owner with Some (Failure text) -> text="original helper error" | _ -> false)
      "original error lost on close uncertainty";
    (try ignore (ValidationStage.path owner);failwith "unknown owner became ordinary getter failure"
     with ValidationStage.Unresolved_ownership _ -> ());
    let sentinel=Filename.concat root "sentinel" in
    let held=List.init 4 (fun _ -> Unix.openfile sentinel [Unix.O_RDWR;Unix.O_CREAT] 0o600) in
    check (List.mem original held) "test did not reuse uncertain numeric fd";
    (try ValidationStage.retire owner;failwith "uncertainty disappeared"
     with ValidationStage.Unresolved_ownership _ -> ());
    List.iter (fun fd -> ignore (Unix.fstat fd);Unix.close fd) held;
    check (bytes source="ORIGINAL GENERATED BYTES") "close fault touched original");
  print_endline "PASS private stage normal/source-rebind/stage-rebind/preentry/collision/source-edit/uncertain-close-no-retry"

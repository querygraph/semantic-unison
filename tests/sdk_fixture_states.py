"""Pure fixed-size scalar states for known generated SDK TIFF/DNG fixtures.

No filesystem/SDK calls. This is a restricted fixture transformer, not a general
TIFF ownership proof, semantic camera recognizer, or receiving admission.
"""
import struct
import xml.etree.ElementTree as ET

MAX_BYTES=128*1048576
MAX_XMP=1048576
COMPRESSION={'uncompressed':1,'jpeg':7,'jxl':52546}
VALUES={'base':('1','Blue'),'left':('2','Blue'),'right':('1','Gold'),'target':('2','Gold')}
RDF='http://www.w3.org/1999/02/22-rdf-syntax-ns#'
XMP='http://ns.adobe.com/xap/1.0/'


def require(value,reason):
    if not value:raise ValueError(reason)


def geometry(data,codec):
    require(type(data) is bytes and 8<=len(data)<=MAX_BYTES,'bounded immutable generated bytes required')
    require(type(codec) is str and codec in COMPRESSION,'three qualified fixture encodings only')
    require(data[:2] in (b'II',b'MM'),'known TIFF byte order required')
    order='<' if data[:2]==b'II' else '>'
    require(struct.unpack_from(order+'H',data,2)[0]==42,'generated classic TIFF layout required')
    primary=struct.unpack_from(order+'I',data,4)[0]
    require(8<=primary<=len(data)-2,'primary directory out of bounds')
    count=struct.unpack_from(order+'H',data,primary)[0];end=primary+2+12*count+4
    require(0<count<=128 and end<=len(data),'bounded complete primary directory required')
    entries={}
    for index in range(count):
        tag,typ,n,value=struct.unpack_from(order+'HHII',data,primary+2+12*index)
        require(tag not in entries,'duplicate generated primary tag')
        entries[tag]=(typ,n,value,primary+2+12*index+8)
    def scalar(tag):
        require(tag in entries,'required generated scalar absent')
        typ,n,value,at=entries[tag]
        require(n==1 and typ in (3,4),'generated scalar type/count differs')
        return struct.unpack_from(order+('H' if typ==3 else 'I'),data,at)[0]
    width,height=scalar(256),scalar(257)
    require((width,height)==(6000,4000),'qualified generated 6000x4000 fixture required')
    require(scalar(259)==COMPRESSION[codec],'declared encoding differs from stored compression')
    require(700 in entries,'generated XMP tag absent')
    typ,size,offset,_=entries[700]
    require(typ==1 and 4<size<=MAX_XMP and offset>=8 and offset+size<=len(data),'bounded out-of-line BYTE XMP required')
    require(offset+size<=primary or offset>=end,'XMP aliases primary structure')
    return dict(width=width,height=height,compression=COMPRESSION[codec],xmp_offset=offset,xmp_size=size)


def xml(packet):
    require(type(packet) is bytes and 0<len(packet)<=MAX_XMP,'bounded XMP packet required')
    require(b'<!DOCTYPE' not in packet and b'<!ENTITY' not in packet,'DTD/entity fixture metadata refused')
    try:root=ET.fromstring(packet.decode('utf-8'))
    except (ET.ParseError,UnicodeDecodeError) as error:raise ValueError('well-formed UTF-8 fixture XMP required') from error
    require(root.tag=='{adobe:ns:meta/}xmpmeta','qualified XMP root required')
    pending=[(root,0)];nodes=0
    while pending:
        node,depth=pending.pop();nodes+=1
        require(depth<=32 and nodes<=65536,'bounded fixture XML tree required')
        pending.extend((child,depth+1) for child in node)
    descriptions=list(root.iter('{'+RDF+'}Description'))
    require(len(descriptions)==1 and descriptions[0].get('{'+RDF+'}about')=='','one qualified empty-about description required')
    return descriptions[0]


def states(data,codec):
    """Insert two disjoint scalars by consuming outside-root XMP padding only.

    Every state retains length, TIFF geometry, and the exact complete complement
    of the XMP range. Opaque metadata is never serialized or normalized.
    """
    observed=geometry(data,codec);offset,size=observed['xmp_offset'],observed['xmp_size'];packet=data[offset:offset+size]
    description=xml(packet)
    scalar_keys=('{'+XMP+'}Rating','{'+XMP+'}Label')
    require(not any(k in description.attrib for k in scalar_keys) and not any(node.tag in scalar_keys for node in description.iter()),'fixture already contains merge scalars')
    anchor=b'rdf:about=""';closing=b'</x:xmpmeta>'
    require(packet.count(anchor)==1 and packet.count(closing)==1,'qualified exact SDK packet spelling required')
    require(b'xmp:Rating=' not in packet and b'xmp:Label=' not in packet,'existing scalar spelling refused')
    base=packet.replace(anchor,anchor+b' xmp:Rating="1" xmp:Label="Blue"',1);growth=len(base)-size
    end=base.index(closing)+len(closing);padding=base.find(b' '*growth,end)
    require(padding>=end,'insufficient outside-root SDK packet padding')
    base=base[:padding]+base[padding+growth:];require(len(base)==size,'fixed XMP size changed')
    variants={}
    for state,(rating,label) in VALUES.items():
        edited=base.replace(b'xmp:Rating="1"',b'xmp:Rating="'+rating.encode()+b'"',1).replace(b'xmp:Label="Blue"',b'xmp:Label="'+label.encode()+b'"',1)
        actual=xml(edited)
        require(actual.get('{'+XMP+'}Rating')==rating and actual.get('{'+XMP+'}Label')==label,'inserted scalar namespace/value differs')
        require(len(edited)==size,'scalar replacement length changed')
        output=data[:offset]+edited+data[offset+size:]
        require(output[:offset]==data[:offset] and output[offset+size:]==data[offset+size:],'outside-XMP bytes changed')
        variants[state]=output
    require(len(set(variants.values()))==4,'four distinct scalar states required')
    return dict(codec=codec,**observed,states=variants)
